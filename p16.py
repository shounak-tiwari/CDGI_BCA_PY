# A laptop costs ₹72,500. The shop gives a 15% discount, then adds 18% GST on the discounted price.
# Calculate: Discount amount , Price after discount , GST amount ,Final price

Selling_Price = 72500
Discount_Amount = (Selling_Price * 15)/100
Price_after_discount = Selling_Price - Discount_Amount
GSTAmount = (Price_after_discount*18)/100
FinalPrice = Price_after_discount+ GSTAmount

print(Discount_Amount)
print(Price_after_discount)
print(GSTAmount)
print(FinalPrice) 
